"""HOOKSHOT_TRACY's zones in the lifted game code (docs/development/tracy.md, The game's own code): a list of lifted
functions that become Tracy zones without translating the game again and without compiling its code again.

The list: nx2/tracy_funcs.txt, and after it the file HOOKSHOT_TRACY_FUNCS names (a list made on this PC from a profile: it is
made from the game and stays here). One function a line:

    <guest address, hex, with or without f_ or 0x> [calls] [the zone's name, in words]

A listed function f_<address> is a zone each time it runs, whoever calls it. How, at the link: in the object of the chunk
that defines it the symbol is made undefined and its code is given the name __real_f_<address> (patch_object: the symbol
table alone is rewritten, into a copy of the object), and a generated C file (wrappers) defines f_<address> as the zone
around a call of __real_f_<address>. Every call in the game (the direct ones of every chunk, its own among them, and the
indirect ones, through a64_table.c) then reaches the wrapper. ELF objects only: Linux.

`calls`: every indirect call (BLR) the function itself makes is a zone too, named by its target (f_<target>) and by the object
it is called on: the game's dispatch points (a job loop running its jobs, a module system its modules). For those the
function's chunk is compiled again (one chunk, not the game) with a header (calls_header) that turns A64_ICALL into a zone
where the call's return address lies in a listed function: the lifted code stores that address as a constant right before the
call, so the test folds away everywhere else and the other functions of the chunk compile as before.

Standard library only; nothing here reads the game's files but the lifted C (for where a function is defined).
"""
import hashlib
import os
import re
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
SEED = os.path.join(HERE, "tracy_funcs.txt")
LINE = re.compile(r"^(?:f_|0x)?([0-9a-fA-F]{6,16})(?:\s+(calls))?(?:\s+(.*))?$")
DEFINED = re.compile(rb"^void (f_[0-9a-f]+)\(Ctx \*__restrict", re.M)


def read_list(paths):
    """[(address, calls, label)] of the lists, in order, a later line for the same address replacing the earlier one"""
    found = {}
    for path in paths:
        with open(path, encoding="utf-8") as f:
            for n, raw in enumerate(f, 1):
                line = raw.split("#", 1)[0].strip()
                if not line:
                    continue
                m = LINE.match(line)
                if not m:
                    raise SystemExit("%s:%d: not '<hex address> [calls] [name]': %s" % (path, n, raw.strip()))
                label = (m.group(3) or "").strip().replace('"', "'").replace("\\", "/")
                found[int(m.group(1), 16)] = (bool(m.group(2)), label)
    return [(addr, calls, label) for addr, (calls, label) in sorted(found.items())]


def list_paths():
    extra = os.environ.get("HOOKSHOT_TRACY_FUNCS", "")
    return [SEED] + ([extra] if extra else [])


def defined_in(chunks, names):
    """{name: chunk source} for the names (f_<address>) the lifted chunks define"""
    want, where = {n.encode() for n in names}, {}
    for src in chunks:
        try:
            with open(src, "rb") as f:
                data = f.read()
        except OSError:
            continue
        for m in DEFINED.finditer(data):
            if m.group(1) in want:
                where[m.group(1).decode()] = src
    return where


def extents(table_c, addrs):
    """{address: size} of the listed functions: up to the next function's address in a64_table.c's list"""
    with open(table_c, "rb") as f:
        every = sorted({int(a, 16) for a in re.findall(rb"\bf_([0-9a-f]{6,16})\b", f.read())})
    out = {}
    for a in addrs:
        later = [x for x in every if x > a]
        out[a] = (later[0] - a) if later else 0x1000
    return out


def name_of(addr):
    return "f_%x" % addr


def wrappers(entries):
    """The generated C: each listed function as a zone around its own code"""
    out = ['/* generated by nx2/tracy_funcs.py (HOOKSHOT_TRACY): the listed lifted functions as Tracy zones */',
           '#include "a64.h"', '#include "hos_tracy.h"',
           'TracyCZoneCtx hos_tracy_fn_begin(const struct ___tracy_source_location_data *loc, Ctx *c, uint64_t addr);',
           'void hos_tracy_fn_end(TracyCZoneCtx *z);']
    for addr, _calls, label in entries:
        n = name_of(addr)
        out.append("void __real_%s(Ctx *A64_NOESC);" % n)
        out.append('void %s(Ctx *__restrict A64_NOESC c) { static const struct ___tracy_source_location_data loc = '
                   '{ "%s", "%s", __FILE__, 0, HT_COLOR_GAME }; TracyCZoneCtx z __attribute__((cleanup(hos_tracy_fn_end))) = '
                   'hos_tracy_fn_begin(&loc, c, 0x%xULL); __real_%s(c); }' % (n, (n + " " + label).strip(), n, addr, n))
    return "\n".join(out) + "\n"


def calls_header(ranges):
    """The header a chunk with `calls` functions is compiled with: A64_ICALL as a zone inside [(address, size)]. The zone
    itself is the host's (host/hos_tracy_game.c): the chunk sees nothing of Tracy"""
    test = " || ".join("(lr) - 0x%xULL < 0x%xULL" % r for r in sorted(ranges))
    return "\n".join([
        "/* generated by nx2/tracy_funcs.py (HOOKSHOT_TRACY): the indirect calls of the listed functions as Tracy zones */",
        '#include "a64.h"',
        "typedef struct { uint64_t w[2]; } HtCallZone;   /* (the host's: host/hos_tracy_game.c) */",
        "HtCallZone hos_tracy_call_begin(Ctx *c, uint64_t target);",
        "void hos_tracy_call_end(HtCallZone *z);",
        "#define HT_CALLS_IN(lr) (%s)" % test,
        "#ifndef A64_NO_SITE_CACHE",
        "#undef A64_ICALL",
        "#define A64_ICALL(c, t) do { \\",
        "    if (HT_CALLS_IN((c)->x[30])) { \\",
        "        HtCallZone ht_cz_ __attribute__((cleanup(hos_tracy_call_end))) = hos_tracy_call_begin((c), (t)); \\",
        "        A64_SITE_CALL(c, t, a64_icall_site); \\",
        "    } else A64_SITE_CALL(c, t, a64_icall_site); \\",
        "} while (0)",
        "#endif", ""])


def patch_object(src, dst, names):
    """dst: the ELF64 object src with each of names (defined global symbols) made undefined and its definition given the
    name __real_<name>. Only the symbol table, its strings and (where the object has one) its section index table are
    written again, after the object's own bytes; returns the names done"""
    with open(src, "rb") as f:
        data = bytearray(f.read())
    if data[:6] != b"\x7fELF\x02\x01":
        raise SystemExit("%s is not a little-endian ELF64 object: the listed functions' zones are Linux's" % src)
    shoff, = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum = struct.unpack_from("<HH", data, 0x3A)
    if shnum == 0:   # (more than 0xff00 sections: the count is section 0's size)
        shnum, = struct.unpack_from("<Q", data, shoff + 0x20)
    SH = "<IIQQQQIIQQ"   # name, type, flags, addr, offset, size, link, info, addralign, entsize
    sections = [list(struct.unpack_from(SH, data, shoff + i * shentsize)) for i in range(shnum)]
    symtab = next(i for i, s in enumerate(sections) if s[1] == 2)
    strtab = sections[symtab][6]
    shndx_tab = next((i for i, s in enumerate(sections) if s[1] == 18 and s[6] == symtab), None)
    sym_off, sym_size = sections[symtab][4], sections[symtab][5]
    strings = bytes(data[sections[strtab][4]:sections[strtab][4] + sections[strtab][5]])
    syms = bytearray(data[sym_off:sym_off + sym_size])
    extra = bytearray(data[sections[shndx_tab][4]:sections[shndx_tab][4] + sections[shndx_tab][5]]) if shndx_tab is not None else None
    want, done, new_strings, new_syms, new_extra = {n.encode(): n for n in names}, [], bytearray(strings), bytearray(), bytearray()
    for i in range(sym_size // 24):
        st_name, st_info, st_other, st_shndx, st_value, st_size = struct.unpack_from("<IBBHQQ", syms, i * 24)
        if st_shndx == 0 or st_info >> 4 != 1:   # (undefined, or not global)
            continue
        end = strings.index(b"\0", st_name)
        name = strings[st_name:end]
        if name not in want:
            continue
        at = len(new_strings)
        new_strings += b"__real_" + name + b"\0"
        new_syms += struct.pack("<IBBHQQ", at, st_info, st_other, st_shndx, st_value, st_size)
        struct.pack_into("<IBBHQQ", syms, i * 24, st_name, 1 << 4, 0, 0, 0, 0)   # (global, no type, undefined)
        if extra is not None:
            new_extra += extra[i * 4:i * 4 + 4]
            struct.pack_into("<I", extra, i * 4, 0)
        done.append(want[name])
    out = bytearray(data)

    def place(index, content, align=8):
        while len(out) % align:
            out.append(0)
        sections[index][4], sections[index][5] = len(out), len(content)
        out.extend(content)

    place(symtab, syms + new_syms)
    place(strtab, new_strings, 1)
    if shndx_tab is not None:
        place(shndx_tab, extra + new_extra, 4)
    for i in (symtab, strtab) + ((shndx_tab,) if shndx_tab is not None else ()):
        struct.pack_into(SH, out, shoff + i * shentsize, *sections[i])
    with open(dst, "wb") as f:
        f.write(out)
    return done


def digest(*parts):
    h = hashlib.sha1(usedforsecurity=False)
    for p in parts:
        h.update(p if isinstance(p, bytes) else str(p).encode())
        h.update(b"\0")
    return h.hexdigest()[:16]
